void setLanguage(const std::string& code) { g_lang = code == "ar" ? "ar" : "en"; }
const std::string& language() { return g_lang; }
bool rtl() { return g_lang == "ar"; }

const char* tr(const char* en) {
    if (g_lang != "ar" || !en) return en;
    const auto& m = arabic();
    const auto it = m.find(en);
    return it == m.end() ? en : it->second;
}

std::string trf(const char* en, ...) {
    char buf[1024];
    va_list ap;
    va_start(ap, en);
    std::vsnprintf(buf, sizeof buf, tr(en), ap);
    va_end(ap);
    return buf;
}

