# Downloads pinned third-party sources listed in third_party.lock and verifies SHA-256.
# Files that already exist with the right hash are skipped. Any mismatch aborts.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$lock = Join-Path $PSScriptRoot 'third_party.lock'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
foreach ($line in Get-Content $lock) {
    if (-not $line.Trim()) { continue }
    $url, $rel, $hash = $line -split ' '
    $dst = Join-Path $root $rel
    if ((Test-Path $dst) -and ((Get-FileHash $dst -Algorithm SHA256).Hash -ieq $hash)) { continue }
    New-Item -ItemType Directory -Force (Split-Path -Parent $dst) | Out-Null
    Write-Host "fetch $rel"
    $tmp = "$dst.part"
    for ($try = 1; $try -le 5; $try++) {
        try { & curl.exe -sSfL --retry 3 -o $tmp $url; if ($LASTEXITCODE -eq 0) { break } } catch { }
        Start-Sleep -Seconds 2
    }
    $got = (Get-FileHash $tmp -Algorithm SHA256).Hash
    if ($got -ine $hash) { Remove-Item $tmp; throw "hash mismatch for $rel" }
    Move-Item -Force $tmp $dst
}
$avconfig = Join-Path $root 'third_party/ffmpeg/include/libavutil/avconfig.h'
if (-not (Test-Path $avconfig)) {
    Set-Content -Encoding ascii $avconfig "/* Generated by WASD (configure output for x86-64 little-endian) */`n#ifndef AVUTIL_AVCONFIG_H`n#define AVUTIL_AVCONFIG_H`n#define AV_HAVE_BIGENDIAN 0`n#define AV_HAVE_FAST_UNALIGNED 1`n#endif"
}
Write-Host 'third-party sources OK'
